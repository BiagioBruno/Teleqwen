import logging

def sum_two_numbers(a: int, b: int) -> int:
    """
    Sum two numbers
    
    Args:
        a: First number
        b: Second number
    """
    logging.info("execute sum_two_numbers tool")
    return a + b

def multiplication_two_numbers(a: int, b: int) -> int:
    """
    Multiplication two numbers
        
    Args:
        a: First number
        b: Second number
    """
    logging.info("execute multiplication_two_numbers tool")
    return a * b